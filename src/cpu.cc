#include "../include/cpu.hh"

namespace cpu {
    void handle_instruction(opcode_t const opcode) {
        switch (opcode) {
        case opcode_t::add: break;
        case opcode_t::sub: break;
        case opcode_t::mul: break;
        case opcode_t::div: break;
        } 
    }
} // namespace cpu
